    w('```')
    w('A>VDPVIEW')
    w('```')
    w('')
    w('| キー | 動作 |')
    w('|---|---|')
    w('| SPACE / RETURN / → | 次のページ |')
    w('| BS / ← | 前のページ |')
    w('| ESC | 終了（画面をテキストに戻して DOS へ） |')
    w('')
    w('- 最後のページで次へ進むと終了します。')
    w('- V9938 では起動しません。V9958 では V9968 専用ページ（タイトルが V9968 で始まるもの）を飛ばします。')
    w('- turboR では Z80 モードに切り替えて実行し、終了時に元の CPU モードに戻します。')
    w('')
    w('## 判定の基本')
